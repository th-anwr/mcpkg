#!/usr/bin/env bash
# Creates .env with random passwords. Run once, in the repo root (e.g. in AWS CloudShell).
#
#   ./scripts/make-env.sh                       # asks for the few things it needs
#   GITHUB_TOKEN=... ./scripts/make-env.sh -y   # non-interactive, defaults for the rest
#
# The same .env is used on every box; push.sh adjusts it per role.
set -euo pipefail
cd "$(dirname "$0")/.."

YES=0; FORCE=0
for a in "$@"; do
  case "$a" in
    -y) YES=1 ;;
    -f) FORCE=1 ;;
    *) echo "usage: make-env.sh [-y] [-f]" >&2; exit 2 ;;
  esac
done
if [ -f .env ] && [ "$FORCE" != 1 ]; then
  echo ".env already exists (use -f to overwrite; your passwords would change)" >&2
  exit 1
fi

ask() { # ask <var> <prompt> <default> [secret]
  local var="$1" prompt="$2" def="$3" secret="${4:-}" val="${!1:-}"
  if [ -z "$val" ] && [ "$YES" != 1 ]; then
    if [ -n "$secret" ]; then read -r -s -p "$prompt: " val; echo; else read -r -p "$prompt [$def]: " val; fi
  fi
  printf -v "$var" '%s' "${val:-$def}"
}

rand() { head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n' | cut -c1-"$1"; }

ask SITE_NAME     "Site name" "mcpkg"
ask SITE_URL      "Public URL (leave 'auto' to use the server's IP for now)" "auto"
ask DOMAIN        "Domain for HTTPS (':80' = plain HTTP on the IP until you have a domain)" ":80"
ask GITHUB_TOKEN  "GitHub token (fine-grained, public repos read-only; needed for health checks)" "" secret
ask CONTACT_EMAIL "Contact email for the crawler User-Agent (optional, registries like crates.io ask for one)" ""
ask LLM_BASE_URL  "LLM base URL (optional, empty = README-based descriptions)" ""

PG_PASS="$(rand 32)"
ADMIN_PASS="$(rand 20)"
# Namespace for trust data in the registry-compatible API: reverse-DNS of the domain (mcpkg.dev -> dev.mcpkg).
if [[ "$DOMAIN" == *.* ]]; then
  NS="$(echo "$DOMAIN" | tr '.' '\n' | tac | paste -sd. -)"
else
  NS="local.$(echo "$SITE_NAME" | tr -cd 'a-z0-9-')"
fi

umask 077
cat > .env <<EOF
# Generated by scripts/make-env.sh on $(date -u '+%Y-%m-%d'). Keep this file private.
SITE_NAME=$SITE_NAME
SITE_URL=$SITE_URL
DOMAIN=$DOMAIN
META_NAMESPACE=$NS
CONTACT_EMAIL=$CONTACT_EMAIL
ADMIN_PASSWORD=$ADMIN_PASS

POSTGRES_PASSWORD=$PG_PASS
DATABASE_URL=postgres://mcpkg:$PG_PASS@db:5432/mcpkg?sslmode=disable

GITHUB_TOKEN=$GITHUB_TOKEN

LLM_BASE_URL=$LLM_BASE_URL
LLM_API_KEY=
LLM_MODEL=openai.gpt-oss-20b
LLM_JSON_MODE=true
LLM_REVIEW_SAMPLE=0.01

SANDBOX=docker
SANDBOX_IMAGE=mcpkg-runner:latest
SANDBOX_RUNTIME=runsc
SANDBOX_EGRESS_NETWORK=mcpkg-egress
SANDBOX_PROXY=http://egress-proxy:3128
SANDBOX_MEMORY=1g
SANDBOX_CPUS=1
LOG_LEVEL=info
LOG_DIR=-
EOF
chmod 600 .env  # umask covers a new file; an existing .env keeps its old mode
echo "wrote .env (admin login for /admin/review: any username, password: $ADMIN_PASS)"
[ -n "$GITHUB_TOKEN" ] || echo "warning: no GITHUB_TOKEN: health checks fall back to 60 requests/hour. Add it to .env before pushing." >&2
